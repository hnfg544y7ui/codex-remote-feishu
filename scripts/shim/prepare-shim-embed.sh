#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PACKAGE_DIR="${ROOT_DIR}/internal/shim/embed"
ASSET_DIR="${PACKAGE_DIR}/assets"
GOOS_VALUE="${1:-${GOOS:-$(go env GOOS)}}"
GOARCH_VALUE="${2:-${GOARCH:-$(go env GOARCH)}}"
SCRIPT_PATH="${BASH_SOURCE[0]}"

if ! command -v zstd >/dev/null 2>&1; then
  echo "zstd is required to prepare shim assets" >&2
  exit 1
fi

checksum_cmd=(sha256sum)
if ! command -v "${checksum_cmd[0]}" >/dev/null 2>&1; then
  checksum_cmd=(shasum -a 256)
fi

checksum_first_field() {
  "${checksum_cmd[@]}" "$1" | awk '{print $1}'
}

tmp_dir="$(mktemp -d)"
generated_go_tmp=""
cleanup() {
  rm -rf "${tmp_dir}"
  if [[ -n "${generated_go_tmp}" ]]; then
    rm -f "${generated_go_tmp}"
  fi
}
trap cleanup EXIT

asset_name="codex-remote-shim-${GOOS_VALUE}-${GOARCH_VALUE}"
binary_path="${tmp_dir}/${asset_name}"
if [[ "${GOOS_VALUE}" == "windows" ]]; then
  binary_path="${binary_path}.exe"
fi

module_path="$(go list -m -f '{{.Path}}')"
dependency_packages="$(CGO_ENABLED=0 GOOS="${GOOS_VALUE}" GOARCH="${GOARCH_VALUE}" go list -deps -f '{{if not .Standard}}{{.ImportPath}}{{end}}' ./cmd/shim)"
source_digest="$(
  {
    printf 'goversion=%s\n' "$(go env GOVERSION)"
    printf 'script=%s\n' "$(checksum_first_field "${SCRIPT_PATH}")"
    printf 'gomod=%s\n' "$(checksum_first_field "${ROOT_DIR}/go.mod")"
    printf 'gosum=%s\n' "$(checksum_first_field "${ROOT_DIR}/go.sum")"
    while IFS= read -r -d '' file; do
      printf '%s  %s\n' "$(checksum_first_field "${file}")" "${file}"
    done < <(
      # The upgrade shim compiles install/config/runtime code too. Hash every
      # repository dependency so a journal/schema/helper change cannot silently
      # reuse an older embedded executable. Import paths avoid host path syntax.
      while IFS= read -r package; do
        case "${package}" in
          "${module_path}") package_dir="${ROOT_DIR}" ;;
          "${module_path}/"*) package_dir="${ROOT_DIR}/${package#"${module_path}/"}" ;;
          *) continue ;;
        esac
        find "${package_dir}" -maxdepth 1 -type f -name '*.go' ! -name '*_test.go' -print0
      done <<< "${dependency_packages}" |
      sort -z
    )
  } | "${checksum_cmd[@]}" | awk '{print $1}'
)"

mkdir -p "${ASSET_DIR}"
compressed_path="${ASSET_DIR}/${asset_name}.zst"
generated_go="${PACKAGE_DIR}/shim_${GOOS_VALUE}_${GOARCH_VALUE}_embed.go"
generated_go_tmp="${generated_go}.tmp.$$"

if [[ -f "${generated_go}" && -f "${compressed_path}" ]] && grep -Fq "SourceDigest: \"${source_digest}\"" "${generated_go}"; then
  echo "shim asset already up to date for ${GOOS_VALUE}/${GOARCH_VALUE}" >&2
  exit 0
fi

CGO_ENABLED=0 GOOS="${GOOS_VALUE}" GOARCH="${GOARCH_VALUE}" \
  go build -trimpath -ldflags "-s -w" -o "${binary_path}" ./cmd/shim

binary_sha256="$(checksum_first_field "${binary_path}")"

zstd -19 -q -f -o "${compressed_path}" "${binary_path}"

cat > "${generated_go_tmp}" <<EOF
// Code generated by scripts/shim/prepare-shim-embed.sh; DO NOT EDIT.

//go:build ${GOOS_VALUE} && ${GOARCH_VALUE}

package embed

import _ "embed"

//go:embed assets/$(basename "${compressed_path}")
var embeddedShim_${GOOS_VALUE}_${GOARCH_VALUE} []byte

func init() {
	register(Asset{
		SourceDigest: "${source_digest}",
		SHA256:       "${binary_sha256}",
		Zstd:         embeddedShim_${GOOS_VALUE}_${GOARCH_VALUE},
	})
}
EOF

gofmt -w "${generated_go_tmp}"
mv "${generated_go_tmp}" "${generated_go}"
echo "prepared shim asset for ${GOOS_VALUE}/${GOARCH_VALUE}" >&2
