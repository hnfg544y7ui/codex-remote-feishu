package install

// The bootstrap receives sensitive launch data only on stdin. The scheduled
// action names a private runner file; neither XML nor argv contains environment.
const windowsUpgradeTaskBootstrapScript = `
[Console]::OutputEncoding=[System.Text.Encoding]::UTF8
[Console]::InputEncoding=[System.Text.Encoding]::UTF8
$ErrorActionPreference='Stop'
$ProgressPreference='SilentlyContinue'
$dir=$null; $name=$null; $registered=$false; $started=$false
try {
  $spec=[Console]::In.ReadToEnd() | ConvertFrom-Json
  $name=[string]$spec.TaskName
  $dir=[string]$spec.ArtifactDir
  if ($name -cnotmatch '^CodexRemoteUpgradeHelper-[a-f0-9]{32}$' -or $dir -cne (Join-Path ([IO.Path]::GetTempPath()) $name)) { throw 'Invalid owned helper launch identity' }
  if ([IO.Directory]::Exists($dir)) { throw 'Private helper directory already exists' }
  [IO.Directory]::CreateDirectory($dir) | Out-Null
  $owner=[Security.Principal.WindowsIdentity]::GetCurrent().User
  $acl=New-Object Security.AccessControl.DirectorySecurity
  $acl.SetOwner($owner)
  $acl.SetAccessRuleProtection($true,$false)
  foreach($sid in @($owner,(New-Object Security.Principal.SecurityIdentifier('S-1-5-18')))) {
    $rule=New-Object Security.AccessControl.FileSystemAccessRule($sid,'FullControl','ContainerInherit,ObjectInherit','None','Allow')
    $acl.AddAccessRule($rule)
  }
  [IO.Directory]::SetAccessControl($dir,$acl)
  $utf8=New-Object Text.UTF8Encoding($false)
  [IO.File]::WriteAllText((Join-Path $dir 'spec.json'),($spec | ConvertTo-Json -Depth 5 -Compress),$utf8)
  [IO.File]::WriteAllText((Join-Path $dir 'runner.ps1'),[string]$spec.RunnerScript,$utf8)
  $exe=Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
  $arguments='-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "'+(Join-Path $dir 'runner.ps1')+'" -ArtifactDir "'+$dir+'" -TaskName '+$name
  $action=New-ScheduledTaskAction -Execute $exe -Argument $arguments -WorkingDirectory ([IO.Path]::GetTempPath())
  $principal=New-ScheduledTaskPrincipal -UserId $owner.Value -LogonType Interactive -RunLevel Limited
  $settings=New-ScheduledTaskSettingsSet -ExecutionTimeLimit ([TimeSpan]::Zero) -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries
  if ([IO.File]::Exists((Join-Path $dir 'cancel'))) { throw 'Helper launch cancelled before registration' }
  Register-ScheduledTask -TaskName $name -Action $action -Principal $principal -Settings $settings | Out-Null
  $registered=$true
  if ([IO.File]::Exists((Join-Path $dir 'cancel'))) { throw 'Helper launch cancelled after registration' }
  Start-ScheduledTask -TaskName $name
  $started=$true
  $deadline=[DateTime]::UtcNow.AddSeconds(20)
  $ackPath=Join-Path $dir 'started.json'
  while (!(Test-Path -LiteralPath $ackPath)) {
    if ([IO.File]::Exists((Join-Path $dir 'cancel'))) { throw 'Helper launch cancelled before acknowledgment' }
    if ([DateTime]::UtcNow -ge $deadline) { throw 'Windows helper did not acknowledge startup within 20 seconds' }
    Start-Sleep -Milliseconds 100
  }
  $ack=Get-Content -LiteralPath $ackPath -Raw -Encoding UTF8 | ConvertFrom-Json
  if ($ack.PID -le 0) { throw 'Independent Windows helper failed to start' }
  @{TaskName=$name; PID=$ack.PID; ArtifactDir=$dir} | ConvertTo-Json -Compress
} catch {
  $message=$_.Exception.Message
  if ($started -and [IO.Directory]::Exists($dir)) {
    [IO.File]::WriteAllText((Join-Path $dir 'cancel'), 'cancel')
    $cleanupDeadline=[DateTime]::UtcNow.AddSeconds(5)
    while ([IO.Directory]::Exists($dir) -and [DateTime]::UtcNow -lt $cleanupDeadline) { Start-Sleep -Milliseconds 100 }
    if ([IO.Directory]::Exists($dir)) { Stop-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue }
  }
  if ($registered) { Unregister-ScheduledTask -TaskName $name -Confirm:$false -ErrorAction SilentlyContinue }
  if ($dir -and [IO.Directory]::Exists($dir)) { [IO.Directory]::Delete($dir,$true) }
  Write-Error $message
  exit 1
}
`

// Cleanup operates only on the identity generated by this Go caller. It allows
// the runner to kill its own gated child before stopping/deleting its task.
const windowsUpgradeTaskCleanupScript = `
[Console]::InputEncoding=[System.Text.Encoding]::UTF8
$ErrorActionPreference='Stop'
$ProgressPreference='SilentlyContinue'
$owned=[Console]::In.ReadToEnd() | ConvertFrom-Json
$name=[string]$owned.TaskName; $dir=[string]$owned.ArtifactDir
if ($name -cnotmatch '^CodexRemoteUpgradeHelper-[a-f0-9]{32}$' -or $dir -cne (Join-Path ([IO.Path]::GetTempPath()) $name)) { throw 'Invalid scoped helper cleanup identity' }
if ([IO.Directory]::Exists($dir)) {
  [IO.File]::WriteAllText((Join-Path $dir 'cancel'),'cancel')
  $deadline=[DateTime]::UtcNow.AddSeconds(5)
  while ([IO.Directory]::Exists($dir) -and [DateTime]::UtcNow -lt $deadline) { Start-Sleep -Milliseconds 100 }
}
for ($attempt=0; $attempt -lt 3; $attempt++) {
  $task=Get-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
  if ($task) {
    Stop-ScheduledTask -TaskName $name -ErrorAction SilentlyContinue
    Unregister-ScheduledTask -TaskName $name -Confirm:$false
  }
  if ([IO.Directory]::Exists($dir)) { [IO.Directory]::Delete($dir,$true) }
  Start-Sleep -Milliseconds 100
}
`

const windowsUpgradeTaskChildScript = `
param([string]$ArtifactDir,[string]$TaskName)
$ErrorActionPreference='Stop'
$ProgressPreference='SilentlyContinue'
$process=$null; $stdout=$null; $stderr=$null
try {
  $spec=Get-Content -LiteralPath (Join-Path $ArtifactDir 'spec.json') -Raw -Encoding UTF8 | ConvertFrom-Json
  Add-Type -TypeDefinition @'
using System;
using System.IO;
using System.Threading.Tasks;
public static class CodexRemoteUpgradePump {
  public static Task Copy(Stream input, Stream output, object mutex) {
    return Task.Factory.StartNew(() => {
      byte[] buffer = new byte[8192]; int length;
      while ((length=input.Read(buffer,0,buffer.Length))>0) {
        lock(mutex) { output.Write(buffer,0,length); output.Flush(); }
      }
    });
  }
}
'@
  $info=New-Object Diagnostics.ProcessStartInfo
  $info.FileName=[string]$spec.BinaryPath
  $info.Arguments=[string]$spec.Arguments
  $info.UseShellExecute=$false; $info.CreateNoWindow=$true
  $info.RedirectStandardInput=$true
  $info.RedirectStandardOutput=$true; $info.RedirectStandardError=$true
  if ($spec.WorkDir) { $info.WorkingDirectory=[string]$spec.WorkDir }
  $info.EnvironmentVariables.Clear()
  foreach($entry in $spec.Env) {
    $offset=0; if ($entry.StartsWith('=')) { $offset=1 }
    $separator=$entry.IndexOf('=',$offset)
    if ($separator -gt 0) { $info.EnvironmentVariables[$entry.Substring(0,$separator)]=$entry.Substring($separator+1) }
  }
  $info.EnvironmentVariables['CODEX_REMOTE_UPGRADE_START_GATE']=Join-Path $ArtifactDir 'receipt'
  $outputPath=[string]$spec.StdoutPath; $errorPath=[string]$spec.StderrPath
  if (!$outputPath) { $outputPath='NUL' }
  if (!$errorPath) { $errorPath=$outputPath }
  foreach($path in @($outputPath,$errorPath)) {
    if ($path -ne 'NUL') { [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName([IO.Path]::GetFullPath($path))) | Out-Null }
  }
  if ($outputPath -eq 'NUL') { $stdout=[IO.Stream]::Null } else { $stdout=[IO.File]::Open($outputPath,[IO.FileMode]::Append,[IO.FileAccess]::Write,[IO.FileShare]::ReadWrite) }
  if ($outputPath -eq $errorPath) { $stderr=$stdout } elseif ($errorPath -eq 'NUL') { $stderr=[IO.Stream]::Null } else { $stderr=[IO.File]::Open($errorPath,[IO.FileMode]::Append,[IO.FileAccess]::Write,[IO.FileShare]::ReadWrite) }
  $process=New-Object Diagnostics.Process
  $process.StartInfo=$info
  if ([IO.File]::Exists((Join-Path $ArtifactDir 'cancel'))) { throw 'Helper startup cancelled' }
  if (!$process.Start()) { throw 'Helper process did not start' }
  $process.StandardInput.Close()
  $mutex=New-Object Object
  $outTask=[CodexRemoteUpgradePump]::Copy($process.StandardOutput.BaseStream,$stdout,$mutex)
  $errTask=[CodexRemoteUpgradePump]::Copy($process.StandardError.BaseStream,$stderr,$mutex)
  $utf8=New-Object Text.UTF8Encoding($false)
  $ackTmp=Join-Path $ArtifactDir 'started.tmp'
  [IO.File]::WriteAllText($ackTmp,(@{PID=$process.Id} | ConvertTo-Json -Compress),$utf8)
  [IO.File]::Move($ackTmp,(Join-Path $ArtifactDir 'started.json'))
  $deadline=[DateTime]::UtcNow.AddSeconds(20)
  while (!(Test-Path -LiteralPath (Join-Path $ArtifactDir 'receipt'))) {
    if ((Test-Path -LiteralPath (Join-Path $ArtifactDir 'cancel')) -or [DateTime]::UtcNow -ge $deadline) { throw 'Helper startup acknowledgment was not received' }
    Start-Sleep -Milliseconds 100
  }
  if ([IO.File]::ReadAllText((Join-Path $ArtifactDir 'receipt')) -ne 'committed') { throw 'Helper startup ownership was not committed' }
  if (!$process.WaitForExit(600000)) { throw 'Upgrade helper exceeded ten-minute execution limit' }
  [Threading.Tasks.Task]::WaitAll(@($outTask,$errTask))
} catch {
  if ($ArtifactDir -and [IO.Directory]::Exists($ArtifactDir)) {
    $failure=Join-Path $ArtifactDir 'started.json'
    if (!(Test-Path -LiteralPath $failure)) {
      [IO.File]::WriteAllText($failure,'{"PID":0}')
      $deadline=[DateTime]::UtcNow.AddSeconds(10)
      while (!(Test-Path -LiteralPath (Join-Path $ArtifactDir 'cancel')) -and [DateTime]::UtcNow -lt $deadline) { Start-Sleep -Milliseconds 100 }
    }
  }
} finally {
  if ($process) {
    try { if (!$process.HasExited) { $process.Kill(); $process.WaitForExit() } } catch {}
    $process.Dispose()
  }
  if ($stderr -and $stderr -ne $stdout) { $stderr.Dispose() }
  if ($stdout) { $stdout.Dispose() }
  Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction SilentlyContinue
  if ($ArtifactDir -and [IO.Directory]::Exists($ArtifactDir)) { [IO.Directory]::Delete($ArtifactDir,$true) }
}
`
